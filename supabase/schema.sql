CREATE OR REPLACE FUNCTION public.reserve_slot(
  p_name TEXT,
  p_email TEXT,
  p_option_id TEXT
)
RETURNS TABLE(status TEXT, option_label TEXT)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  option_record public.options%ROWTYPE;
BEGIN
  SELECT * INTO option_record
  FROM public.options
  WHERE id = p_option_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RETURN QUERY SELECT 'missing'::TEXT, NULL::TEXT;
    RETURN;
  END IF;

  IF EXISTS (SELECT 1 FROM public.submissions WHERE email = p_email) THEN
    RETURN QUERY SELECT 'duplicate'::TEXT, option_record.label;
    RETURN;
  END IF;

  IF option_record.taken >= option_record.capacity THEN
    RETURN QUERY SELECT 'full'::TEXT, option_record.label;
    RETURN;
  END IF;

  BEGIN
    INSERT INTO public.submissions (name, email, option_id)
    VALUES (p_name, p_email, p_option_id);
  EXCEPTION WHEN unique_violation THEN
    RETURN QUERY SELECT 'duplicate'::TEXT, option_record.label;
    RETURN;
  END;

  UPDATE public.options SET taken = taken + 1 WHERE id = p_option_id;
  RETURN QUERY SELECT 'ok'::TEXT, option_record.label;
END;
$$;

CREATE OR REPLACE FUNCTION public.cancel_slot(p_submission_id BIGINT)
RETURNS TABLE(status TEXT)
LANGUAGE plpgsql
SET search_path = ''
AS $$
DECLARE
  selected_option_id TEXT;
BEGIN
  DELETE FROM public.submissions
  WHERE id = p_submission_id
  RETURNING option_id INTO selected_option_id;

  IF NOT FOUND THEN
    RETURN QUERY SELECT 'missing'::TEXT;
    RETURN;
  END IF;

  UPDATE public.options SET taken = taken - 1 WHERE id = selected_option_id;
  RETURN QUERY SELECT 'ok'::TEXT;
END;
$$;

